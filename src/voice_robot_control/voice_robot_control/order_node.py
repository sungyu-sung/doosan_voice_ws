#!/usr/bin/env python3
"""
order_node.py — ⑨ 말로 시키는 로봇 (팀 프로젝트)

말로 물어보고, 듣고, 시킨 작업을 한다.

    ros2 launch voice_robot_control order.launch.py

동작 순서:

    말한다        "어떤 동작을 원하시나요?"
      ↓
    듣는다        사람 → "콜라"
      ↓
    고른다        if 콜라  → 작업1_하기()
                  if 사이다 → 작업2_하기()
      ↓
    한다          작업마다 자기 블록이 따로 있습니다   ← 한 줄씩 쌓습니다
      ↓
    다시 처음으로

■ 실습 — 고칠 곳은 두 군데입니다
  1. 맨 위    작업 이름(작업1_이름 ...)과 좌표(좌표1, 좌표2 ...)
  2. 아래     작업1_하기() / 작업2_하기() 안의 블록

  블록은 줄을 지우거나, 순서를 바꾸거나, 새 줄을 끼워 넣으면
  그대로 동작이 바뀝니다. time.sleep 의 숫자도 직접 고치세요.

  좌표는 이렇게 알아냅니다.
      ros2 launch voice_robot_control viewer.launch.py
  로봇 팔을 손으로 그 자리에 갖다 대고, 화면에 나온 x y z 를 적으세요.
  손목 각도는 화면의 '손목 각도  degree=' 값을 그대로 적으면 됩니다.
  (잘 모르겠으면 0 으로 두고 시작하세요)

■ 말하고 싶은 게 있으면 print 대신 말하기 를 쓰세요
      말하기("안녕하세요")
      말하기("남은 개수는", 3, "개입니다")
  화면에도 같이 찍히니 print 를 따로 쓸 필요가 없습니다.

■ 집게는 그리퍼(폭) 하나로 열고 닫습니다
      그리퍼(500)            50mm 로 벌린다 (놓기)
      그리퍼(150)            15mm 로 좁힌다 (잡기)
      그리퍼(150, 100)       좁히되 약하게 (10N)
  아래 놓을_폭 / 잡을_폭 / 잡는_힘 을 고치면 한 곳에서 다 바뀝니다.

■ 로봇 없이 자리에서 연습하려면
      로봇_사용 = False   로 바꾸고 실행하세요 (말하고 듣는 것만 됩니다).
"""

import time

from .core.blocks import (
    준비, 말하기, 듣기, 홈으로, 이동, 그리퍼, 끝내기,
)


# ══════════════════════════════════════════════════════════
#  ▼▼▼ 여기를 바꿔가며 연습하세요 ▼▼▼
# ══════════════════════════════════════════════════════════

# ── 1. 무슨 말을 들으면 어떤 작업을 할까요? ───────────────
#      "콜라", "1번", "왼쪽" 처럼 아무 말이나 넣어도 됩니다.
작업1_이름 = "콜라"
작업2_이름 = "사이다"

# ── 2. 좌표  (base_link 기준, 단위 m) ─────────────────────
#      물건 바로 위를 한 번 들렀다가 내려가야 옆에서 부딪히지 않습니다.
#      그래서 '위' 자리와 '물건' 자리를 따로 적습니다. (z 만 다릅니다)
#
#      권장 범위   x      :  0.30 ~ 0.60    앞으로 나간 거리
#                  y      : -0.30 ~ 0.30    왼쪽(+) / 오른쪽(-)
#                  z      :  0.27 ~ 0.60    높이
#                  degree : -180 ~ 180      집게를 돌리는 각도 [도]
#      x < 0, |y| > 0.3, z < 0.27 은 자동으로 잘리고 경고가 뜹니다.
#      너무 멀면(팔 길이 0.9m) 범위 안이어도 "계획 실패" 가 뜹니다.
#
#      degree 는 손목(link_6)을 돌리는 각도입니다. 단위는 도°.
#      물건이 비스듬히 놓여 있으면 집게를 그만큼 돌려서 잡습니다.
#        0 = 지금까지와 같음      90 = 집게를 90도 돌려서
#      안 적으면 0 으로 봅니다.

# 작업 1 에서 쓰는 자리
좌표1 = {"x": 0.393, "y":  0.094, "z": 0.330, "degree": 0}    # 집을 물건 위
좌표2 = {"x": 0.393, "y":  0.094, "z": 0.280, "degree": 0}    # 집을 물건
좌표3 = {"x": 0.393, "y": -0.206, "z": 0.330, "degree": 0}    # 놓을 자리 위
좌표4 = {"x": 0.393, "y": -0.206, "z": 0.280, "degree": 0}    # 놓을 자리

# 작업 2 에서 쓰는 자리
좌표5 = {"x": 0.392, "y":  0.200, "z": 0.330, "degree": 0}    # 집을 물건 위
좌표6 = {"x": 0.392, "y":  0.200, "z": 0.280, "degree": 0}    # 집을 물건
좌표7 = {"x": 0.392, "y": -0.101, "z": 0.330, "degree": 0}    # 놓을 자리 위
좌표8 = {"x": 0.392, "y": -0.101, "z": 0.280, "degree": 0}    # 놓을 자리

# ── 3. 집게를 얼마나 벌리고 얼마나 세게 쥘까? ─────────────
#      ※ 단위가 1/10 입니다.  500 = 50mm,  300 = 30N
#         (EGP-C 40 은 열기/닫기뿐이라 폭 325 이상이면 열고 미만이면 닫습니다. 힘은 무시됩니다)
#
#      잡을_폭 은 물건보다 좁아야 합니다. 물건보다 넓으면 집게가 겉만
#      스치고 지나가서 "물건을 못 잡은 것 같습니다" 가 뜹니다.
놓을_폭 = 500        # 50mm — 놓을 때 벌리는 폭
잡을_폭 = 150        # 15mm — 잡을 때 좁히는 폭
잡는_힘 = 300        # 30N  — 약한 물건이면 100(10N) 정도로 줄이세요

# ── 안내 멘트 ────────────────────────────────────────────
질문_멘트 = f"어떤 동작을 원하시나요? {작업1_이름}, {작업2_이름} 중에 골라 주세요."
못_알아들었을_때 = "죄송합니다. 다시 한 번 말씀해 주세요."
끝인사 = "네, 그만하겠습니다. 수고하셨습니다."

# 이 말을 들으면 프로그램을 끝냅니다
그만_할_때 = "그만"

# ── 연습용 스위치 ────────────────────────────────────────
로봇_사용 = True      # False → 팔을 안 움직이고 화면에만 찍습니다
마이크_사용 = True    # False → 마이크 대신 /stt_result 를 기다립니다

# ══════════════════════════════════════════════════════════


# ══════════════════════════════════════════════════════════
#   작업 1 —  "콜라" 라고 하면 이 블록들이 실행됩니다
#            ↓ 여기를 바꾸면 작업 1 의 동작이 바뀝니다
# ══════════════════════════════════════════════════════════
def 작업1_하기():
    말하기(f"{작업1_이름} 시작하겠습니다. 잠시만 기다려 주세요.")

    그리퍼(놓을_폭)         # 집게를 열고
    time.sleep(1.0)

    이동(좌표1)            # 물건 위로 가서
    time.sleep(1.0)

    이동(좌표2)            # 내려가서
    time.sleep(1.0)

    그리퍼(잡을_폭, 잡는_힘)  # 잡고
    time.sleep(1.0)

    이동(좌표1)            # 들어 올리고
    time.sleep(1.0)

    이동(좌표3)            # 놓을 자리 위로 옮기고
    time.sleep(1.0)

    이동(좌표4)            # 내려가서
    time.sleep(1.0)

    그리퍼(놓을_폭)         # 놓고
    time.sleep(1.0)

    이동(좌표3)            # 빠져나오고
    time.sleep(1.0)

    홈으로()               # 제자리로 돌아간다

    말하기(f"{작업1_이름} 끝났습니다.")


# ══════════════════════════════════════════════════════════
#   작업 2 —  "사이다" 라고 하면 이 블록들이 실행됩니다
#            ↓ 작업 1 과 아주 다른 동작을 넣어도 됩니다
# ══════════════════════════════════════════════════════════
def 작업2_하기():
    말하기(f"{작업2_이름} 시작하겠습니다. 잠시만 기다려 주세요.")

    그리퍼(놓을_폭)         # 집게를 열고
    time.sleep(1.0)

    이동(좌표5)            # 물건 위로 가서
    time.sleep(1.0)

    이동(좌표6)            # 내려가서
    time.sleep(1.0)

    그리퍼(잡을_폭, 잡는_힘)  # 잡고
    time.sleep(1.0)

    이동(좌표5)            # 들어 올리고
    time.sleep(1.0)

    이동(좌표7)            # 놓을 자리 위로 옮기고
    time.sleep(1.0)

    이동(좌표8)            # 내려가서
    time.sleep(1.0)

    그리퍼(놓을_폭)         # 놓고
    time.sleep(1.0)

    이동(좌표7)            # 빠져나오고
    time.sleep(1.0)

    홈으로()               # 제자리로 돌아간다

    말하기(f"{작업2_이름} 끝났습니다.")


# ══════════════════════════════════════════════════════════
#   물어보고 → 듣고 → 어느 작업인지 고른다
# ══════════════════════════════════════════════════════════
def 한_번_받기():
    # ── 1. 물어본다 ────────────────────────────────
    말하기(질문_멘트)

    # ── 2. 듣는다 ──────────────────────────────────
    손님_말 = 듣기()

    # ── 3. 고른다   ← if 문 ────────────────────────
    if 그만_할_때 in 손님_말:
        말하기(끝인사)
        return False                  # False = 이제 그만

    elif 작업1_이름 in 손님_말:
        작업1_하기()                  # ← 작업 1 의 블록이 실행됩니다

    elif 작업2_이름 in 손님_말:
        작업2_하기()                  # ← 작업 2 의 블록이 실행됩니다

    # 작업을 늘리려면 여기에 한 덩이를 더 붙이면 됩니다.
    #
    #   elif 작업3_이름 in 손님_말:
    #       작업3_하기()

    else:
        말하기(못_알아들었을_때)

    return True                       # True = 다시 물어본다


# ══════════════════════════════════════════════════════════
#  여기부터는 안 건드려도 됩니다
# ══════════════════════════════════════════════════════════
def main(args=None):
    준비(로봇=로봇_사용, 마이크=마이크_사용)

    홈으로()          # 시작하기 전에 자세를 잡는다

    try:
        계속하기 = True
        while 계속하기:
            계속하기 = 한_번_받기()
    except KeyboardInterrupt:
        pass

    끝내기()


if __name__ == "__main__":
    main()
